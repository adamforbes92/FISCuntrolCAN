const uint8_t* getBootLogoBitmap(uint8_t bootScreenId) {
    switch (bootScreenId) {
        case 2:
            return MK4Golf;
        case 3:
            return logo;
        case 4:
            return finger;
    case 5:
      return customBootLogoLoaded ? customBootLogo : nullptr;
        default:
            return nullptr;
    }
}

bool loadCustomBootLogo() {
  File logoFile = LittleFS.open(customBootLogoPath, "r");
  if (!logoFile) {
    customBootLogoLoaded = false;
    return false;
  }

  if (logoFile.size() != (size_t)bootLogoBufferSize) {
    logoFile.close();
    customBootLogoLoaded = false;
    return false;
  }

  const bool ok = logoFile.read(customBootLogo, bootLogoBufferSize) == (int)bootLogoBufferSize;
  logoFile.close();
  customBootLogoLoaded = ok;
  return ok;
}

bool hasCustomBootLogo() {
  return customBootLogoLoaded;
}

bool saveCustomBootLogoFromBmp(const char* bmpPath) {
  File bmpFile = LittleFS.open(bmpPath, "r");
  if (!bmpFile) {
    return false;
  }

  if (bmpFile.size() != bootLogoBufferSize) {
    bmpFile.close();
    return false;
  }

  uint8_t convertedLogo[bootLogoBufferSize];
  const bool readOk = bmpFile.read(convertedLogo, bootLogoBufferSize) == (int)bootLogoBufferSize;
  bmpFile.close();

  if (!readOk) {
    return false;
  }

  File outFile = LittleFS.open(customBootLogoPath, "w");
  if (!outFile) {
    return false;
  }

  const bool written = outFile.write(convertedLogo, bootLogoBufferSize) == bootLogoBufferSize;
  outFile.close();

  if (!written) {
    return false;
  }

  memcpy(customBootLogo, convertedLogo, bootLogoBufferSize);
  customBootLogoLoaded = true;
  return true;
}

